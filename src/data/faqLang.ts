// src/data/faqLang.ts
//
// Question-shaped FAQ pages in the Indian languages.
//
// 🔑 WHY. Search Console, three months to 2026-10-16: 111 impressions, average
// position 6.2, CTR 17.1%, and **seven queries in total** — six of them the
// brand name or a misspelling. The site ranks and converts and is simply never
// shown, because nothing on it answers anything people type. `/faq` (English)
// was the first page built in the one shape that has ever worked here. This is
// the same shape in the eleven Indian languages, which is the real edge:
// *"মানসিক স্বাস্থ্য অ্যাপ"* and its equivalents have a fraction of the
// competition of their English counterparts, in markets where Imotara is one of
// very few options at all.
//
// ⛔ THE EXISTING /hi /bn /ta PAGES ARE NOT THIS. They are brand pages —
// organised around what Imotara wants to SAY. They stay as they are; these are
// new routes at /faq/<lang>. Nothing that already works was touched.
//
// ⚠️ THE REGISTER IS NOT INVENTED HERE. It follows
// src/lib/legal/consentCopy.ts, which carries the same voice in all 22
// languages and has shipped, been read by users and been corrected by the
// owner. Fresh prose in eleven scripts would have drifted from the product.
//
// 🔴 EVERY `crisis` ANSWER NAMES THE RIGHT COUNTRY'S NUMBERS, not India's by
// default. A language is not a country: Bengali is also Bangladesh, Tamil is
// also Sri Lanka and Singapore, Urdu is mostly Pakistan, Punjabi is both. The
// numbers below are copied from src/lib/safety/crisisResources.ts — never
// typed from memory — and every answer also names findahelpline.com for
// anywhere else. ⇒ the lesson in imotaraapp 3ef1937, where an undetected
// country was shown Indian numbers and ~140 countries were shown none.
//
// ⛔ HOUSE RULES, enforced by src/__tests__/faqLangHonesty.test.ts:
//   · every language covers the SAME eight topic ids, so none can quietly rot
//   · every question ends in that script's question mark
//   · every answer is written in its own script — a copy-paste from the
//     neighbouring language is the likeliest way this file breaks
//   · never claim to be therapy; the age is 13 with parental consent under 18,
//     in that language's own digits
//   · the crisis answer names a real service and says Imotara is not one

export type LangFaqItem = {
    /** ⛔ Shared across every language. A missing id fails the test. */
    id: LangFaqTopic;
    /** Must end in the script's question mark. */
    q: string;
    /** First sentence answers it completely; an AI surface quotes one answer. */
    a: string;
};

