export type LangFaq = {
    /** BCP-47 primary subtag, and the URL segment: /faq/bn */
    lang: string;
    /** The language's name in itself — what a reader recognises. */
    nativeName: string;
    /** English name, for the hreflang switcher on the other pages. */
    englishName: string;
    /** `lang` attribute direction. */
    dir: "ltr" | "rtl";
    /** ⚠️ OpenGraph locale, so the right regional audience is targeted. */
    ogLocale: string;
    title: string;
    description: string;
    /** One sentence under the h1. Not a pitch. */
    intro: string;
    /** The h1. A question-shaped page deserves a question-shaped heading. */
    heading: string;
    items: LangFaqItem[];
};

